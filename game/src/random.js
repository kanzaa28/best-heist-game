// Seeded RNG (mulberry32), so a screenshot staged from a seed always replays the
// same way. Only the camera sweep phase and cosmetic sparkle use it; the rules are
// deterministic without it.

/** A small fast seeded PRNG. */
export function mulberry32(seed) {
  let a = seed >>> 0;
  return function next() {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
